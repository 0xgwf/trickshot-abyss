const cache = new Map<string, HTMLCanvasElement>();

/** Returns a 16×16 canvas for the sprite (white when flashing, optionally palette-swapped). */
export function sprite(name: string, flash = false, tint?: Tint): HTMLCanvasElement {
  const key = `${name}#${flash ? 'f' : ''}#${tint ?? ''}`;
  let c = cache.get(key);
  if (c) return c;
  const rows = SPRITES[name] ?? SPRITES.warrior;
  c = document.createElement('canvas');
  c.width = 16;
  c.height = 16;
  const ctx = c.getContext('2d')!;
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch === '.') return;
      ctx.fillStyle = flash ? '#ffffff' : (tint && TINTS[tint][ch]) || PALETTE[ch] || '#ff00ff';
      ctx.fillRect(x, y, 1, 1);
    });
  });
  cache.set(key, c);
  return c;
}

export const hasSprite = (name: string) => name in SPRITES;
